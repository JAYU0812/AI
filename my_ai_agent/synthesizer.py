    def propose_edit(
        self,
        feature_request: str,
        target_file: str,
        existing_code: str,
    ) -> EditProposal:
        """Produce a structured EditProposal with atomic operations."""
        from my_ai_agent.editing.edit_operations import (
            EditOperation,
            EditOperationType,
            EditProposal,
            FileEditProposal,
        )

        req_lower = feature_request.lower()
        ops: List[EditOperation] = []

        # 1. Target Class Detection (e.g. "Add a logout method to AuthService")
        target_class = None
        for m in re.finditer(r"\bto\s+([A-Z][a-zA-Z0-9_]*)\b", feature_request):
            c_name = m.group(1)
            if f"class {c_name}" in existing_code:
                target_class = c_name
                break

        # Check if single class in existing code
        if not target_class:
            class_matches = re.findall(r"^class\s+([A-Z][a-zA-Z0-9_]*)\b", existing_code, re.MULTILINE)
            if len(class_matches) == 1 and any(k in req_lower for k in ("method", "class")):
                target_class = class_matches[0]

        # 2. Case: "Add a uuid based session ID to login"
        if "uuid" in req_lower and "login" in req_lower:
            login_code = '''def login(self, username, password):
    self.session_id = str(uuid.uuid4())
    return username == "admin"'''
            ops.append(EditOperation(
                operation_type=EditOperationType.REPLACE,
                target_file=target_file,
                target_symbol="login",
                content=login_code,
                required_imports=["import uuid"],
                description="Add UUID-based session ID to login method",
            ))
            return EditProposal(
                intent="MODIFY_METHOD",
                description=f"Add UUID-based session ID to login in {target_file}",
                files=[FileEditProposal(path=target_file, operations=ops)],
            )

        # 3. Case: Logout (Method vs Top-Level Function)
        if "logout" in req_lower:
            if target_class:
                logout_method = '''def logout(self, *args, **kwargs) -> bool:
    """Terminates an authenticated user session."""
    self.session = None
    return True'''
                ops.append(EditOperation(
                    operation_type=EditOperationType.INSERT,
                    target_file=target_file,
                    target_symbol=target_class,
                    content=logout_method,
                    description=f"Insert logout method into {target_class}",
                ))
            else:
                logout_func = '''def logout(username: str = "current_user") -> bool:
    """Terminates an authenticated user session."""
    print(f"[Auth] User '{username}' logged out successfully.")
    return True'''
                ops.append(EditOperation(
                    operation_type=EditOperationType.INSERT,
                    target_file=target_file,
                    content=logout_func,
                    description="Insert top-level logout function",
                ))
            return EditProposal(
                intent="ADD_METHOD" if target_class else "ADD_FUNCTION",
                description=f"Add logout to {target_class or target_file}",
                files=[FileEditProposal(path=target_file, operations=ops)],
            )

        # 4. Case: Login
        if "login" in req_lower:
            if target_class:
                login_method = '''def login(self, username: str, password: str = "") -> bool:
    """Authenticates user credentials."""
    return username == "admin"'''
                ops.append(EditOperation(
                    operation_type=EditOperationType.INSERT,
                    target_file=target_file,
                    target_symbol=target_class,
                    content=login_method,
                    description=f"Insert login method into {target_class}",
                ))
            else:
                login_func = '''def login(username: str, password: str = "") -> bool:
    """Authenticates user credentials."""
    print(f"[Auth] Authenticating user '{username}'...")
    return bool(username and (password or True))'''
                ops.append(EditOperation(
                    operation_type=EditOperationType.INSERT,
                    target_file=target_file,
                    content=login_func,
                    description="Insert top-level login function",
                ))
            return EditProposal(
                intent="ADD_METHOD" if target_class else "ADD_FUNCTION",
                description=f"Add login to {target_class or target_file}",
                files=[FileEditProposal(path=target_file, operations=ops)],
            )

        # 5. Generic Feature / Function
        words = [w for w in re.findall(r"[a-zA-Z0-9]+", req_lower) if w not in ("add", "a", "an", "the", "function", "method", "to", "in", "it", "code")]
        slug = "_".join(words[:3]) or "new_feature"
        
        if target_class:
            method_code = f'''def {slug}(self, *args, **kwargs):
    """Implementation for: {feature_request}."""
    return True'''
            ops.append(EditOperation(
                operation_type=EditOperationType.INSERT,
                target_file=target_file,
                target_symbol=target_class,
                content=method_code,
                description=f"Insert {slug} method into {target_class}",
            ))
        else:
            func_code = f'''def {slug}(*args, **kwargs):
    """Implementation for: {feature_request}."""
    print(f"Executing {slug}...")
    return True'''
            ops.append(EditOperation(
                operation_type=EditOperationType.INSERT,
                target_file=target_file,
                content=func_code,
                description=f"Insert {slug} function",
            ))

        return EditProposal(
            intent="ADD_METHOD" if target_class else "ADD_FUNCTION",
            description=f"Add {slug} to {target_class or target_file}",
            files=[FileEditProposal(path=target_file, operations=ops)],
        )
